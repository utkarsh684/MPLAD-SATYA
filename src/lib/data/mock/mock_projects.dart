  /// Get projects by risk level.
  static List<ProjectModel> byRisk(String level) {
    switch (level) {
      case 'Critical':
        return all.where((p) => p.riskScore >= 81).toList();
      case 'High':
        return all.where((p) => p.riskScore >= 61 && p.riskScore < 81).toList();
      case 'Medium':
        return all.where((p) => p.riskScore >= 31 && p.riskScore < 61).toList();
      case 'Low':
        return all.where((p) => p.riskScore < 31).toList();
      default:
        return all;
    }
  }

